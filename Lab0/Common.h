#pragma once

// Общие вспомогательные функции, которые понадобятся больше чем в одном задании
// (в первую очередь написанные для Задания 2, но повторно используемые в Задании 5 -
// методичка прямо просит не дублировать код, а передавать уже написанные функции
// в новые задачи, работающие с той же логикой, но с массивом в динамической памяти).
//
// Обратите внимание: сюда сознательно вынесены только "чистые" функции обработки
// массива (принимают указатель на массив + размер, ничего сами не печатают и не
// содержат cin/cout) - вывод и ввод остаются в Task2_*/Task5_* функциях. Это разделение
// как раз то, о чём говорится в разделе "Функции" методички: не дублировать логику.

// Сортировка массива int по возрастанию (Задание 2.1). Алгоритм на ваш выбор
// (пузырёк, выбор, любой другой) - в задании это не регламентируется.
void SortIntArray(int* array, int size);

// Аналогичная сортировка для double (нужна в Задании 5.4).
void SortDoubleArray(double* array, int size);

// Подсчитывает количество элементов array, которые >= searchingValue (Задание 2.2).
int CountAboveOrEqual(const double* array, int size, double searchingValue);

// Линейный поиск значения searchingValue в array. Возвращает индекс первого
// совпадения или -1, если значение не найдено (используется в Задании 5.5).
int FindIndex(const int* array, int size, int searchingValue);

// Подсчитывает количество букв ('a'-'z' и 'A'-'Z', с учётом регистра при сравнении)
// среди символов массива (Задание 2.3 / переиспользуется в Задании 5.6).
int CountLetters(const char* array, int size);

// Печать массива в одну строку через пробел, со std::endl в конце.
// Отдельная функция под каждый тип, так как шаблоны (template) в этой лабе не изучаются.
void PrintIntArray(const int* array, int size);
void PrintDoubleArray(const double* array, int size);
void PrintBoolArray(const bool* array, int size);
void PrintCharArray(const char* array, int size);
